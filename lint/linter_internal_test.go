package lint

import (
	"strings"
	"testing"
)

func BenchmarkIsGenerated(b *testing.B) {
	body := strings.Repeat("func foo() {}\n", 10_000)
	benchmarks := []struct {
		name string
		src  string
	}{
		{"generated", "// Code generated by some tool. DO NOT EDIT.\n\npackage foo\n\n" + body},
		{"non-generated", "// Copyright 2026.\n\n// Package foo.\npackage foo\n\n" + body},
		{"line longer than 64 KiB", "// " + strings.Repeat("a", 64*1024) + "\n// Code generated by some tool. DO NOT EDIT.\npackage foo\n\n" + body},
	}
	for _, bb := range benchmarks {
		b.Run(bb.name, func(b *testing.B) {
			src := []byte(bb.src)
			b.ReportAllocs()
			for b.Loop() {
				isGenerated(src)
			}
		})
	}
}
